"""Reproduce the reviewed, read-only upstream subset; never import upstream packages."""
import ast
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / 'research/wechatauto-replica'
TARGET = ROOT / 'chattrace/vendor'


def main():
    TARGET.mkdir(exist_ok=True)
    source = (UPSTREAM / 'wechatauto/db.py').read_text('utf-8-sig')
    tree = ast.parse(source)
    prefix = source[:source.index('def _looks_like_text')]
    prefix = prefix.replace('from wechatauto.logger import wxlog', '')
    # The upstream reverse scan can read eight bytes beyond the module image.
    prefix = prefix.replace('range(len(image) - 8, 0, -8)', 'range(len(image) - 16, 0, -8)')
    dbclass = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == 'WeChatDB')
    methods = [n for n in dbclass.body if isinstance(n, ast.FunctionDef) and n.name in
               {'_collect_key_candidates', '_probable_key', '_find_bytes'}]
    scanner = ast.ClassDef(name='KeyScanner', bases=[], keywords=[], body=methods, decorator_list=[])
    header = '# Generated by tools/vendor_readonly.py; do not edit. Apache-2.0, see LICENSE-wechatauto.\n'
    bindings = '\n_k32.CloseHandle.argtypes = [wintypes.HANDLE]\n_k32.CloseHandle.restype = wintypes.BOOL\n'
    (TARGET / 'wcdb_readonly.py').write_text(header + prefix + bindings + '\n' + ast.unparse(scanner) + '\n', 'utf-8')
    (TARGET / '__init__.py').write_text('', 'utf-8')
    shutil.copyfile(UPSTREAM / 'LICENSE', TARGET / 'LICENSE-wechatauto')
    shutil.copyfile(ROOT / 'research/WeChatMsg-v3/LICENSE', TARGET / 'LICENSE-WeChatMsg')
    for name in ('packed_info_data_img2_pb2.py', 'packed_info_data_img_pb2.py'):
        shutil.copyfile(ROOT / 'research/WeChatMsg-v3/wxManager/parser/util/protocbuf' / name, TARGET / name)


if __name__ == '__main__':
    main()
